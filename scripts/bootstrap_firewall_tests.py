def _test_iptables_guards(tmp: Path, failures: list[str]) -> None:
    # Fix 3: no LOG rule (operator deleted it) or no rules.v4, but the epoch
    # marker is present: check mode, never a flush.
    for name, content in (
        ("no LOG rule", "-A INPUT -p tcp --dport 8080 -j ACCEPT\n"),
        ("no file", None),
    ):
        root, env = _board(tmp, f"ipt-marked-{name.replace(' ', '-')}")
        Path(env["SYSTEM_EPOCH_FILE"]).write_text("6\n")
