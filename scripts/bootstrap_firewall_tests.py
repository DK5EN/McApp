def _test_ssh_ports(tmp: Path, failures: list[str]) -> None:
    # Fix 6: non-22 sshd ports get an accept on the wholesale paths.
    root, env = _board(tmp, "nft-port")
    r = _nft(root, env, {"STUB_SSHD_PORTS": "22 2222 2222 2200"})
    conf = Path(env["MCAPP_NFT_CONF"])
    _check(
        r.returncode == 0
        and conf.read_text() == _expected_nft(env["MCAPP_NFT_CUSTOM_DIR"], ("2222", "2200")),
        f"nft fresh: Port 2222/2200 accepted once each (rc {r.returncode})",
        failures,
    )
    _check(
        "tcp dport 22 ct state new" in conf.read_text(), "nft fresh: port 22 rules kept", failures
    )

    for name, extra in (("sshd-fails", {"STUB_SSHD_RC": "1"}),):
        root, env = _board(tmp, f"nft-{name}")
        r = _nft(root, env, extra)
        _check(
            r.returncode == 0
            and Path(env["MCAPP_NFT_CONF"]).read_text()
            == _expected_nft(env["MCAPP_NFT_CUSTOM_DIR"]),
            f"nft {name}: nothing added, no abort",
            failures,
        )
    # A failing sshd -T is not silent: only 22 is open and the operator must know.
    root, env = _board(tmp, "nft-sshd-warns")
    r = _nft(root, env, {"STUB_SSHD_RC": "1"})
    _check("sshd -T" in r.stderr, f"nft sshd fails: warning missing ({r.stderr})", failures)
    # The port can come from a ListenAddress, a capitalised key (newer OpenSSH) or the
    # session we are running in. Each alone must still open it.
    for name, extra, port in (
        ("listen", {"STUB_SSHD_RAW": "listenaddress 0.0.0.0:2222"}, "2222"),
        ("listen6", {"STUB_SSHD_RAW": "listenaddress [::]:2223"}, "2223"),
        ("capital", {"STUB_SSHD_RAW": "Port 2224"}, "2224"),
        ("session", {"SSH_CONNECTION": "192.168.1.20 50000 192.168.1.55 2225"}, "2225"),
    ):
        root, env = _board(tmp, f"nft-ssh-{name}")
        r = _nft(root, env, extra)
        _check(
            r.returncode == 0
            and Path(env["MCAPP_NFT_CONF"]).read_text()
            == _expected_nft(env["MCAPP_NFT_CUSTOM_DIR"], (port,)),
            f"nft ssh {name}: port {port} opened once (rc {r.returncode})",
            failures,
        )
    # Values no real sshd prints must not reach the ruleset: an invalid port makes
    # nft refuse the whole file, and 022 is just port 22.
    for name, value in (
        ("too-big", "a b c 99999"),
        ("huge", "a b c 99999999999999999999"),
        ("zero", "a b c 0"),
        ("octal-22", "a b c 022"),
        ("words", "a b c garbage"),
        ("empty", ""),
    ):
        root, env = _board(tmp, f"nft-ssh-bad-{name}")
        r = _nft(root, env, {"SSH_CONNECTION": value})
        _check(
            r.returncode == 0
            and Path(env["MCAPP_NFT_CONF"]).read_text()
            == _expected_nft(env["MCAPP_NFT_CUSTOM_DIR"]),
            f"nft ssh {name}: no extra rule (rc {r.returncode})",
            failures,
        )
    # A ListenAddress without a port adds nothing.
    root, env = _board(tmp, "nft-ssh-noport")
    r = _nft(root, env, {"STUB_SSHD_RAW": "listenaddress 192.168.1.55\nlistenaddress ::"})
    _check(
        Path(env["MCAPP_NFT_CONF"]).read_text() == _expected_nft(env["MCAPP_NFT_CUSTOM_DIR"]),
        "nft ssh: ListenAddress without a port adds nothing",
        failures,
    )
    # sshd absent from PATH altogether.
    root, env = _board(tmp, "nft-nosshd")
    (root / "bin" / "sshd").unlink()
    r = _nft(root, env, {"PATH": f"{root / 'bin'}:/usr/bin:/bin"})
    _check(
        r.returncode == 0
        and Path(env["MCAPP_NFT_CONF"]).read_text() == _expected_nft(env["MCAPP_NFT_CUSTOM_DIR"]),
        f"nft sshd absent: nothing added, no abort (rc {r.returncode}: {r.stderr})",
        failures,
    )

    # Bookworm first install: the extra port sits right after the port-22 accept.
    root, env = _board(tmp, "ipt-port")
    r = _ipt(root, env, {"STUB_SSHD_PORTS": "22 2222"})
    got = [c for c in _ipt_calls(root) if c.startswith("-A INPUT ")]
    want = list(_IPT_FIRST_INSTALL)
    want.insert(want.index("-p tcp --dport 22 -j ACCEPT") + 1, "-p tcp --dport 2222 -j ACCEPT")
    _check(
        r.returncode == 0 and got == [f"-A INPUT {w}" for w in want],
        f"ipt first install: Port 2222 accepted after the 22 rule (rc {r.returncode})",
        failures,
    )
    root, env = _board(tmp, "ipt-sshd-fails")
    r = _ipt(root, env, {"STUB_SSHD_RC": "1"})
    got = [c for c in _ipt_calls(root) if c.startswith("-A INPUT ")]
    _check(
        r.returncode == 0 and got == [f"-A INPUT {w}" for w in _IPT_FIRST_INSTALL],
        "ipt first install: failing sshd adds nothing, no abort",
        failures,
    )
    # Check mode only adds what McApp owns: no extra port.
    root, env = _board(tmp, "ipt-check-port")
    Path(env["MCAPP_IPT_RULES"]).parent.mkdir(parents=True)
    Path(env["MCAPP_IPT_RULES"]).write_text(_IPT_OLD_RULES)
    _ipt(root, env, {"STUB_SSHD_PORTS": "22 2222"})
    _check(
        not any("2222" in c for c in _ipt_calls(root)),
        "ipt check mode: no extra ssh port rule",
        failures,
    )


def _test_dropin(tmp: Path, failures: list[str]) -> None:
    root, env = _board(tmp, "dropin")
    Path(env["MCAPP_NFT_CONF"]).write_text(_MARKED)
    _nft(root, env)
    drop = Path(env["MCAPP_NFT_DROPIN_DIR"]) / "mcapp-fallback.conf"
    conf = env["MCAPP_NFT_CONF"]
    cdir = env["MCAPP_NFT_CUSTOM_DIR"]
    want = (
        "[Service]\nExecStart=\n"
        f"ExecStart=/bin/sh -c '/usr/sbin/nft -f {conf} || {{ echo \"McApp: nftables.conf failed, "
        f'retrying without custom rules" >&2; sed "\\#{cdir}#d" {conf} | /usr/sbin/nft -f -; }}\'\n'
    )
    _check(
        drop.is_file() and drop.read_text() == want,
        f"dropin: expected ExecStart (got {drop.read_text() if drop.is_file() else None!r})",
        failures,
    )
    _check(
        sum("daemon-reload" in c for c in _calls(root)) == 1, "dropin: daemon-reload once", failures
    )
    _nft(root, env)
    _check(
        sum("daemon-reload" in c for c in _calls(root)) == 1,
        "dropin: rerun, no second daemon-reload",
        failures,
    )
    drop.parent.mkdir(parents=True, exist_ok=True)
    drop.write_text("stale\n")
    _nft(root, env)
    _check(drop.read_text() == want, "dropin: changed content rewritten", failures)
    _check(
        sum("daemon-reload" in c for c in _calls(root)) == 2,
        "dropin: daemon-reload on change",
        failures,
    )


def _no_destructive(ipt: list[str]) -> bool:
    return not any(c.split()[0] in ("-F", "-X", "-P") for c in ipt)


