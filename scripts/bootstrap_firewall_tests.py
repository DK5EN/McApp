        _check(
            not Path(env["MCAPP_NFT_DROPIN_DIR"]).exists(), f"{name}: no drop-in written", failures
        )
        _check(
            not list(root.glob("nftables.conf.mcapp-new")), f"{name}: no leftover temp", failures
        )


