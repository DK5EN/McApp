def _test_operator_file(tmp: Path, failures: list[str]) -> None:
    # Field report 2026-11-06: a converge replaced an operator's 1273-byte file with
    # our rules and closed :8080. A file with real rules and no marker is theirs.
    root, env = _board(tmp, "operator")
    conf = Path(env["MCAPP_NFT_CONF"])
    conf.write_text(_OPERATOR_FILE)
    r = _nft(root, env)
    calls = _calls(root)
    _check(r.returncode == 0, f"operator file: rc {r.returncode}", failures)
    _check(conf.read_text() == _OPERATOR_FILE, "operator file: byte-identical", failures)
    _check(
        _no_verb(calls, "reload", "restart", "reload-or-restart", "enable", "start"),
        f"operator file: firewall service untouched: {calls}",
        failures,
    )
    _check(
        not any(c.startswith("nft -f") for c in calls),
        f"operator file: nothing loaded: {calls}",
        failures,
    )
    _check(
        not (Path(env["MCAPP_NFT_DROPIN_DIR"]) / "mcapp-fallback.conf").exists(),
        "operator file: no drop-in",
        failures,
    )
    _check(
        "keeping" in r.stderr and "2985" in r.stderr and "loopback" in r.stderr,
        f"operator file: warns and names what McApp needs ({r.stderr})",
        failures,
    )
    _check(
        not Path(env["MCAPP_NFT_CUSTOM_DIR"]).exists(),
        "operator file: no custom folder, nothing would include it",
        failures,
    )
    # Shapes with no accept rule that are still somebody's firewall.
    for name, text in (
        (
            "deny-all",
            _DEBIAN_DEFAULT.replace(
                "hook input priority filter;", "hook input priority filter; policy drop;"
            ),
        ),
        (
            "deny-forward",
            _DEBIAN_DEFAULT.replace(
                "hook forward priority filter;", "hook forward priority filter; policy drop;"
            ),
        ),
        ("one-liner", "table inet f; add rule inet f input tcp dport 8080 accept\n"),
    ):
        root, env = _board(tmp, f"operator-{name}")
        conf = Path(env["MCAPP_NFT_CONF"])
        conf.write_text(text)
        r = _nft(root, env)
        _check(conf.read_text() == text, f"operator {name}: kept (rc {r.returncode})", failures)
    # A file we cannot judge is kept, never replaced. Root reads anything, so skip there.
    if os.geteuid() != 0:
        root, env = _board(tmp, "operator-unreadable")
        conf = Path(env["MCAPP_NFT_CONF"])
        conf.write_text(_OPERATOR_FILE)
        conf.chmod(0)
        r = _nft(root, env)
        conf.chmod(0o644)
        _check(conf.read_text() == _OPERATOR_FILE, "unreadable file: kept", failures)
    # A big file: a grep pipeline under pipefail would misread this through SIGPIPE.
    root, env = _board(tmp, "operator-big")
    conf = Path(env["MCAPP_NFT_CONF"])
    big = (
        _OPERATOR_FILE
        + "".join(f"# filler {n}\n" for n in range(20000))
        + "\n".join(f"    tcp dport {n} accept" for n in range(10000, 12000))
    )
    conf.write_text(big)
    r = _nft(root, env)
    _check(conf.read_text() == big, f"big operator file: kept (rc {r.returncode})", failures)
    # An explicit stock policy is still no rule of its own.
    root, env = _board(tmp, "policy-only")
    conf = Path(env["MCAPP_NFT_CONF"])
    conf.write_text(_DEBIAN_DEFAULT.replace("priority filter;", "priority filter; policy accept;"))
    r = _nft(root, env)
    _check(
        conf.read_text() == _expected_nft(env["MCAPP_NFT_CUSTOM_DIR"]),
        "stock file with an explicit policy: replaced",
        failures,
    )
    # Debian's stock file has no rules: it is replaced on a fresh box, as before.
    root, env = _board(tmp, "debian-default")
    conf = Path(env["MCAPP_NFT_CONF"])
    conf.write_text(_DEBIAN_DEFAULT)
    r = _nft(root, env)
    _check(
        r.returncode == 0 and conf.read_text() == _expected_nft(env["MCAPP_NFT_CUSTOM_DIR"]),
        f"debian default: replaced (rc {r.returncode})",
        failures,
    )
    _check("keeping" not in r.stderr, f"debian default: no keep warning: {r.stderr}", failures)


