def _check(ok: bool, label: str, failures: list[str]) -> None:
    if not ok:
        failures.append(label)


def _write_stub(bin_dir: Path, name: str, body: str) -> None:
    path = bin_dir / name
    path.write_text("#!/bin/bash\n" + body)
    path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def _board(tmp: Path, name: str) -> tuple[Path, dict[str, str]]:
    """A scratch board: stubs on PATH plus every overridable path redirected."""
    root = tmp / name
    bin_dir = root / "bin"
    bin_dir.mkdir(parents=True)
    log = 'echo "$(basename "$0") $*" >> "$CALLS"\n'
    _write_stub(
        bin_dir,
        "systemctl",
        log + 'if [ "$1" = "is-active" ]; then exit "${STUB_INACTIVE:-0}"; fi\nexit 0\n',
    )
    # nft -c fails on STUB_NFT_C_RC, or when an operator file in the custom
    # folder contains the word BAD (a faulty custom include).
    _write_stub(
        bin_dir,
        "nft",
        log + 'if [ "$1" = "-c" ]; then\n'
        '  if [ "$3" = "$MCAPP_NFT_CONF" ]; then\n'
        '    echo "stub: checked the live file" >&2; exit 1\n'
        "  fi\n"
        '  cp "$3" "$CALLS.checked"\n'
        '  if grep -qs BAD "$MCAPP_NFT_CUSTOM_DIR"/*.nft; then\n'
        '    echo "stub nft error: BAD custom file" >&2; exit 1\n'
        "  fi\n"
        '  [ "${STUB_NFT_C_RC:-0}" = 0 ] || echo "stub nft error" >&2\n'
        '  exit "${STUB_NFT_C_RC:-0}"\n'
        "fi\n"
        "exit 0\n",
    )
    _write_stub(
        bin_dir,
        "iptables",
        log + 'if [ "$1" = "-C" ]; then exit "${STUB_C_RC:-1}"; fi\n'
        'if [ "$1" = "-S" ]; then printf \'%s\\n\' "${STUB_IPT_S:--P INPUT DROP}"; fi\n'
        "exit 0\n",
    )
    _write_stub(
        bin_dir,
        "iptables-save",
        log + 'echo "# live rules incl. custom"\nexit "${STUB_SAVE_RC:-0}"\n',
    )
    _write_stub(
        bin_dir,
        "sshd",
        '[ "${STUB_SSHD_RC:-0}" = 0 ] || exit "$STUB_SSHD_RC"\n'
        'for p in ${STUB_SSHD_PORTS:-22}; do echo "port $p"; done\n'
        'echo "addressfamily any"\n'
        '[ -z "${STUB_SSHD_RAW:-}" ] || printf \'%s\\n\' "$STUB_SSHD_RAW"\n',
    )
    for stub in ("apt-get", "debconf-set-selections"):
        _write_stub(bin_dir, stub, log + "exit 0\n")
    _write_stub(bin_dir, "dpkg", log + "exit 0\n")
    _write_stub(bin_dir, "date", "echo 20260101\n")
    (root / "calls.log").write_text("")
    env = {
        "PATH": f"{bin_dir}:/usr/bin:/bin:/usr/sbin:/sbin",
        "HOME": str(root),
        "TMPDIR": str(root),
        "LIB_DIR": str(_LIB),
        "CALLS": str(root / "calls.log"),
        "LANG": "C",
        "MCAPP_NFT_CONF": str(root / "nftables.conf"),
        "MCAPP_NFT_CUSTOM_DIR": str(root / "mcapp" / "nftables.d"),
        "MCAPP_NFT_DROPIN_DIR": str(root / "nftables.service.d"),
        "MCAPP_IPT_RULES": str(root / "iptables" / "rules.v4"),
        "MCAPP_CONFIG_BACKUP_DIR": str(root / "backups"),
        "SYSTEM_EPOCH_FILE": str(root / "system-epoch"),
    }
    return root, env


def _run(
    root: Path, env: dict[str, str], script: str, extra: dict[str, str] | None = None
) -> subprocess.CompletedProcess[str]:
    driver = root / "driver.sh"
    driver.write_text(_PRELUDE + script)
    assert _BASH is not None
    return subprocess.run(  # noqa: S603 - fixed argv, _BASH is a resolved absolute path
        [_BASH, str(driver)],
        env={**env, **(extra or {})},
        capture_output=True,
        text=True,
        timeout=60,
        check=False,
    )


def _calls(root: Path) -> list[str]:
    return (root / "calls.log").read_text().splitlines()


def _nft(
    root: Path, env: dict[str, str], extra: dict[str, str] | None = None
) -> subprocess.CompletedProcess[str]:
    return _run(root, env, "configure_nftables\n", extra)


def _ipt(
    root: Path, env: dict[str, str], extra: dict[str, str] | None = None
) -> subprocess.CompletedProcess[str]:
    return _run(root, env, "configure_iptables_legacy\n", extra)


def _ipt_calls(root: Path) -> list[str]:
    return [c.split(None, 1)[1] for c in _calls(root) if c.startswith("iptables ")]


def _no_verb(calls: list[str], *verbs: str) -> bool:
    return not any(c.startswith(f"systemctl {v} ") for c in calls for v in verbs)


def _expected_nft(inc: str, ports: tuple[str, ...] = ()) -> str:
    extra = "".join(f"\n    # SSH on a non-default port\n    tcp dport {p} accept\n" for p in ports)
    return _NFT_EXPECTED.replace("@EXTRA@", extra).replace("@INC@", inc)


def _expected_migrated(text: str, inc: str, keep_flush: bool = False) -> str:
    out = text.replace(
        "    tcp dport 80 accept\n", f'    tcp dport 80 accept\n    include "{inc}/*.nft"\n', 1
    )
    if not keep_flush:
        out = out.replace("flush ruleset\n", "table inet filter\ndelete table inet filter\n", 1)
    return out


def _read(p: Path) -> str:
    return p.read_text(encoding="utf-8")


def _test_existing_marked(tmp: Path, failures: list[str]) -> None:
    root, env = _board(tmp, "existing")
    conf = Path(env["MCAPP_NFT_CONF"])
    conf.write_text(_MARKED)
    r = _nft(root, env)
    inc = env["MCAPP_NFT_CUSTOM_DIR"]
    _check(r.returncode == 0, f"existing: rc 0 (got {r.returncode}: {r.stderr})", failures)
    _check(
        conf.read_text() == _expected_migrated(_MARKED, inc),
        "existing: only include + delete-table idiom changed",
        failures,
    )
    _check("destroy" not in conf.read_text(), "existing: no destroy in migrated file", failures)
    _check(_CUSTOM_LINE in conf.read_text(), "existing: custom line survives", failures)
    _check(conf.read_text().count("include ") == 1, "existing: include added once", failures)
    calls = _calls(root)
    _check("systemctl reload nftables" in calls, "existing: reload called", failures)
    _check(_no_verb(calls, "restart", "enable"), "existing: never restart or enable", failures)
    _check("nft -c -f" in " ".join(calls), "existing: staged file validated", failures)
    _check(
        (Path(inc) / "custom.nft.example").is_file() and not list(Path(inc).glob("*.nft")),
        "existing: example written, nothing loadable",
        failures,
    )
    backups = list(Path(env["MCAPP_CONFIG_BACKUP_DIR"]).glob("*nftables.conf*"))
    _check(
        any(b.read_text() == _MARKED for b in backups),
        "backup: a copy of the old conf exists",
        failures,
    )
    # Rerun: nothing changes, no reload, no daemon-reload.
    before = conf.read_text()
    n = len(_calls(root))
    r = _nft(root, env)
    _check(r.returncode == 0 and conf.read_text() == before, "rerun: file unchanged", failures)
    new = _calls(root)[n:]
    _check(not any(c.startswith("systemctl reload") for c in new), "rerun: no reload", failures)
    _check(not any("daemon-reload" in c for c in new), "rerun: no daemon-reload", failures)
    _check("already configured" in r.stdout, "rerun: says already configured", failures)


def _test_flush_kept(tmp: Path, failures: list[str]) -> None:
    root, env = _board(tmp, "twotables")
    text = _MARKED + "\ntable ip nat {\n}\n"
    conf = Path(env["MCAPP_NFT_CONF"])
    conf.write_text(text)
    r = _nft(root, env)
    want = _expected_migrated(text, env["MCAPP_NFT_CUSTOM_DIR"], keep_flush=True)
    _check(
        r.returncode == 0 and conf.read_text() == want,
        "second table: flush kept, include added",
        failures,
    )

    # Fix 8: a top-level include may hold other tables, so the flush stays.
    root, env = _board(tmp, "topinclude")
    text = _MARKED + 'include "/etc/nftables.d/*.nft"\n'
    conf = Path(env["MCAPP_NFT_CONF"])
    conf.write_text(text)
    r = _nft(root, env)
    want = _expected_migrated(text, env["MCAPP_NFT_CUSTOM_DIR"], keep_flush=True)
    _check(
        r.returncode == 0 and conf.read_text() == want,
        f"top-level include: flush kept (rc {r.returncode})",
        failures,
    )
    _check("delete table" not in conf.read_text(), "top-level include: no delete idiom", failures)

    # An INDENTED include (inside a chain) is not top-level: still migrated.
    root, env = _board(tmp, "indentinclude")
    text = _MARKED.replace(
        "    tcp dport 8080 accept\n", '    tcp dport 8080 accept\n    include "/etc/x/*.nft"\n'
    )
    conf = Path(env["MCAPP_NFT_CONF"])
    conf.write_text(text)
    _nft(root, env)
    _check(
        "delete table inet filter" in conf.read_text(),
        "indented include: flush still replaced",
        failures,
    )


def _test_validation(tmp: Path, failures: list[str]) -> None:
    root, env = _board(tmp, "invalid")
    conf = Path(env["MCAPP_NFT_CONF"])
    conf.write_text(_MARKED)
    r = _nft(root, env, {"STUB_NFT_C_RC": "1"})
    _check(r.returncode == 0, f"nft -c fails: rc 0 (got {r.returncode})", failures)
