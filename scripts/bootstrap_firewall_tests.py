"""Startup regression suite for the firewall section of bootstrap/lib/system.sh.

Field problem: the bootstrap destroyed operators' own firewall rules
(``iptables -F`` on every run, ``flush ruleset`` plus a full rewrite for
nftables, ``systemctl restart nftables`` whose ExecStop flushes every table).

Rules pinned here, against the REAL bash functions with stub binaries on PATH.
Lockout-critical output (the generated ruleset, the Bookworm rule list) is
compared EXACTLY, so deleting a single rule fails the suite.

Trixie (``configure_nftables``)
1. A marked file with no legacy trigger is never rewritten: custom lines survive
   byte-identical, one include of the custom folder is added after the HTTP
   rule, ``flush ruleset`` becomes ``table inet filter`` + ``delete table inet
   filter`` (portable; ``destroy`` needs kernel 6.3+ and appears nowhere), kept
   when the file owns another table or has a top-level include, ``reload`` is
   used and ``restart`` never. A rerun changes nothing and does not reload.
2. The staged copy is validated (``nft -c`` and a ``dport 22`` rule) before it
   replaces the live file; a failure leaves the file untouched and returns 0.
3. An inactive service on a marked file is left off: no enable/start/reload.
4. A fresh or unmarked box gets the generated file, validated with ``nft -c``
   BEFORE it replaces the old one (a failing check keeps the old file and
   applies nothing), ``enable`` + ``reload-or-restart``; a legacy marked file is
   rewritten with a warning and no ``enable``. A backup of the old file is kept.
5. The boot-fallback drop-in is written once.
6. Wholesale paths add an accept for every non-22 sshd port (``sshd -T``).

Bookworm (``configure_iptables_legacy``)
7. First install only when the rules file lacks the LOG prefix AND the epoch
   marker is absent: flush, rules, then policies. Otherwise add-only (``-C`` or
   ``-A``): no flush, no policy, an open INPUT chain stays open, a failed
   ``iptables-save`` keeps the old rules file.

Set BOOTSTRAP_FIREWALL_LIB_DIR to point the suite at another lib dir (used to
prove the tests fail against a mutated or pre-change system.sh).
"""

