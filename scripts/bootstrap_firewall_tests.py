def _marked_for_check() -> str:
    return (
        _expected_nft("/nowhere")
        .replace("table inet filter\ndelete table inet filter\n", "flush ruleset\n")
        .replace('    include "/nowhere/*.nft"\n', "")
    )


def run_bootstrap_firewall_tests() -> bool:
    if _BASH is None:
        print("bootstrap_firewall: SKIP (no bash)")
        return True
    failures: list[str] = []
    groups = (
        _test_existing_marked,
        _test_flush_kept,
        _test_validation,
        _test_inactive,
        _test_fresh,
        _test_full_write_validation,
        _test_operator_file,
        _test_validated_is_installed,
        _test_legacy,
        _test_ssh_ports,
        _test_dropin,
        _test_iptables_existing,
        _test_iptables_guards,
        _test_iptables_first_install,
    )
    with tempfile.TemporaryDirectory(prefix="mcapp-firewall-") as td:
        tmp = Path(td)
        for group in groups:
            group(tmp, failures)
    for f in failures:
        print(f"  FAIL: {f}")
    print(f"bootstrap_firewall: {len(failures)} failure(s) across {len(groups)} case groups")
    return not failures


if __name__ == "__main__":
    raise SystemExit(0 if run_bootstrap_firewall_tests() else 1)
